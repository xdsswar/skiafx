#!/usr/bin/env python3
# Restored for jux-engine build (original from gclient).
# Helper to locate node_modules paths. Called by tools/typescript/ts_library.py
# and other Chromium build scripts.

import os
import sys

_HERE_DIR = os.path.dirname(os.path.abspath(__file__))
_NODE_MODULES_DIR = os.path.join(_HERE_DIR, 'node_modules')


def GetNodeModulesPath():
    return _NODE_MODULES_DIR


def PathToTypescript():
    """Returns the path to the tsc binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'typescript', 'bin', 'tsc')


def PathToEsbuild():
    """Returns the path to the esbuild binary inside node_modules."""
    if sys.platform == 'win32':
        return os.path.join(_NODE_MODULES_DIR, '.package',
                            'esbuild@0.20.2', 'node_modules', 'esbuild',
                            'esbuild.exe')
    return os.path.join(_NODE_MODULES_DIR, 'esbuild', 'bin', 'esbuild')


def PathToRollup():
    """Returns the path to the rollup binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'rollup', 'dist', 'bin', 'rollup')


def PathToTerser():
    """Returns the path to the terser binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'terser', 'bin', 'terser')


def PathToTsProto():
    """Returns the path to the ts-proto binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'ts-proto', 'protoc-gen-ts_proto')


def PathToEsLint():
    """Returns the path to the eslint binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'eslint', 'bin', 'eslint.js')


def PathToStylelint():
    """Returns the path to the stylelint binary inside node_modules."""
    return os.path.join(_NODE_MODULES_DIR, 'stylelint', 'bin', 'stylelint.mjs')


if __name__ == '__main__':
    print(GetNodeModulesPath())
